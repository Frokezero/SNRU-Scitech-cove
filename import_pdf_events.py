def parse_events(text):
    lines = text.strip().split('\n')
    new_events = []
    
    for line in lines:
        parts = line.split(' ', 2)
        if len(parts) < 3: continue
        
        idx = parts[0]
        date_part = parts[1]
        rest = parts[2]
        
        # Check if the date_part is actually a date or part of a longer title
        # This is a bit tricky with Thai OCR
        if not any(m in date_part for m in ['ม.ค.', 'ก.พ.', 'มี.ค.', 'เม.ย.', 'พ.ค.', 'มิ.ย.', 'ก.ค.', 'ส.ค.', 'ก.ย.', 'ต.ค.', 'พ.ย.', 'ธ.ค.', 'เม.ย.']):
             # If date is not in parts[1], it might be in rest, or parts[1] might be part of date
             # Let's try a different split
             parts = line.split(' ', 3)
             if len(parts) >= 4 and any(m in parts[1] + ' ' + parts[2] for m in ['ม.ค.', 'ก.พ.']):
                 date_part = parts[1] + ' ' + parts[2]
                 rest = parts[3]
        
        # Clean title and detect category
        title = rest.split('เสร็จสิ้น')[0].strip()
        status = "เสร็จสิ้น" if "เสร็จสิ้น" in rest else "รอการดำเนินการ"
        category = "กิจกรรมสาขาวิชา" if "*" in title else "กิจกรรมมหาวิทยาลัย"
        owner = "คณะวิทยาศาสตร์และเทคโนโลยี" if category == "กิจกรรมสาขาวิชา" else "แอดมินส่วนกลาง"
        
        # Determine score
        score = 20
        if "กีฬา" in title or "ค่าย" in title: score = 50
        if "ปฐมนิเทศ" in title or "ไหว้ครู" in title: score = 30
        
        new_events.append({
            "id": str(uuid.uuid4()),
            "date": date_part,
            "title": title.replace('*', ''),
            "status": status,
            "score": score,
            "owner": owner,
            "category": category
        })
    
    return new_events

if __name__ == "__main__":
    extracted = parse_events(ocr_text)
    
    # Load existing events
